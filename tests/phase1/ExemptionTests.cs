    /// <summary>A generated suffix and a marker independently cannot hide a real custom-rule violation.</summary>
    [Fact, Trait("Case", "R-50.negative")]
    public void Generate_FakeSuffixOrMarker_RetainsExactDiagnostic()
    {
        var fixture = new BuildFixture();
        fixture.Restore();
        (int Exit, string Output) clean = fixture.Build();
        clean.Exit.ShouldBe(expected: 0, customMessage: clean.Output);
        string source = BuildFixture.CleanSource.Replace(oldValue: "        return 1;",
                newValue: new string(c: '\n', count: 60) + "        return 1;",
                comparisonType: StringComparison.Ordinal);
        fixture.Write(source: source);
        string normal = Path.Combine(path1: fixture.DirectoryPath, path2: "src/core/Subject.cs");
        string fake = Path.Combine(path1: fixture.DirectoryPath, path2: "src/core/Subject.g.cs");
        File.Move(sourceFileName: normal, destFileName: fake);
        (int Exit, string Output) suffix = fixture.Build();
        BuildFixture.HasDiagnostic(result: suffix, id: "SCR0006", line: 6, column: 25, file: "Subject.g.cs")
                .ShouldBeTrue(customMessage: suffix.Output);
        ExemptionValidator.CheckSource(path: "Subject.g.cs", content: source).ShouldContain(
                expected: "GENERATION_UNPROVEN Subject.g.cs(1,1) generated filename", comparer: StringComparer.Ordinal);
        File.Move(sourceFileName: fake, destFileName: normal);
        string marker = "// <auto-generated/>\n" + source;
        fixture.Write(source: marker);
        (int Exit, string Output) marked = fixture.Build();
        BuildFixture.HasDiagnostic(result: marked, id: "SCR0006", line: 7, column: 25).ShouldBeTrue(
                customMessage: marked.Output);
        ExemptionValidator.CheckSource(path: "Subject.cs", content: marker).ShouldContain(
                expected: "GENERATION_UNPROVEN Subject.cs(1,1) generated marker", comparer: StringComparer.Ordinal);
        ProofProtocol.Record(id: "R-50.negative", diagnostic: "FAKE_GENERATION_REJECTED",
                location: fixture.DirectoryPath + "/src/core/Subject.g.cs(6,25) and Subject.cs(7,25)");
    }

    /// <summary>Semantic resolution sees aliased suppression attributes while literal samples remain inert.</summary>
    [Fact, Trait("Case", "rules.suppression-semantic")]
    public void Suppress_AliasedOrUnconditionalAttribute_RejectsUndeclaredScope()
    {
        foreach (string type in new[] { "SuppressMessageAttribute", "UnconditionalSuppressMessageAttribute" })
        {
            string source = "using Hidden = System.Diagnostics.CodeAnalysis." + type + ";\n"
                    + "[assembly: Hidden(\"ApiDesign\", \"RS0030\", Scope=\"namespace\", Target=\"~N:Sample\")]\n"
                    + "namespace Sample; class Subject {}\n";
            IReadOnlyList<string> errors = ExemptionValidator.CheckSource(path: "Subject.cs", content: source);
            errors.Count.ShouldBe(expected: 1);
            errors[0].ShouldBe(expected: "SUPPRESSION_UNREGISTERED Subject.cs(2,12) RS0030");
        }

        ExemptionValidator.CheckSource(path: "Subject.cs", content: "class Subject { const string Sample = "
                + "\"#pragma warning disable SCR0006 [SuppressMessage] // <auto-generated/>\"; }").ShouldBeEmpty();
        ProofProtocol.Record(id: "rules.suppression-semantic", diagnostic: "SUPPRESSION_SEMANTIC_EXACT",
                location: "Subject.cs(2,12), aliases and unconditional attributes; quoted samples unchanged");
    }

    /// <summary>Duplicate exact member attributes fail before permission set conversion can hide overlap.</summary>
    [Fact, Trait("Case", "rules.suppression-duplicate")]
    public void Suppress_DuplicateObservedAttribute_RejectsOverlap()
    {
        const string Path = "tests/phase1/GeneratedCallSiteAdapters.cs";
        string source = File.ReadAllText(path: System.IO.Path.Combine(path1: ProofProtocol.Root, path2: Path));
        IReadOnlySet<string> permissions = ExemptionValidator.ReadPermissions();
        ExemptionValidator.CheckSource(path: Path, content: source, permissions: permissions).ShouldBeEmpty();
        string duplicate = source + source[source.IndexOf(value: "[assembly:",
                comparisonType: StringComparison.Ordinal)..];
        IReadOnlyList<string> errors = ExemptionValidator.CheckSource(path: Path, content: duplicate,
                permissions: permissions);
        errors.Count.ShouldBe(expected: 4);
        errors.All(predicate: error => error.StartsWith(value: "SUPPRESSION_DUPLICATE " + Path + "(",
                comparisonType: StringComparison.Ordinal)).ShouldBeTrue();
        ProofProtocol.Record(id: "rules.suppression-duplicate", diagnostic: "SUPPRESSION_DUPLICATE",
                location: "four independently duplicated exact registered member attributes");
    }

    /// <summary>Actual editor policy passes; every severity weakening and fake generated section fails.</summary>
    [Fact, Trait("Case", "rules.suppression-configuration")]
    public void Configure_UndeclaredWeakening_RejectsExactSetting()
    {
        string policy = File.ReadAllText(path: Path.Combine(path1: ProofProtocol.Root, path2: ".editorconfig"));
        ExemptionValidator.CheckEditorConfig(path: ".editorconfig", content: policy, requirePermissions: true)
                .ShouldBeEmpty();
        foreach (string level in new[] { "none", "silent", "suggestion", "warning" })
        {
            string source = "root = true\n[*.cs]\ndotnet_diagnostic.SCR0006.severity = " + level + "\n";
            IReadOnlyList<string> errors = ExemptionValidator.CheckEditorConfig(path: "Subject.editorconfig",
                    content: source);
            errors.Count.ShouldBe(expected: 1);
            errors[0].ShouldBe(expected: "SUPPRESSION_CONFIG Subject.editorconfig(3,1) "
                    + "[*.cs]|dotnet_diagnostic.scr0006.severity");
        }

        ExemptionValidator.CheckEditorConfig(path: ".editorconfig", content: policy
                + "\n[*.g.cs]\ngenerated_code = true\n").Count.ShouldBe(expected: 1);
        ExemptionValidator.CheckEditorConfig(path: ".editorconfig", content: policy
                + "\n[tests/phase1/**.cs]\ndotnet_diagnostic.CA1707.severity = none\n")
                .Count.ShouldBe(expected: 1);
        ProofProtocol.Record(id: "rules.suppression-configuration", diagnostic: "SUPPRESSION_CONFIG",
                location: "actual exact permissions, severity neighbors, generated claim and duplicate setting");
    }

