    /// <summary>A changed copied task binary is rejected before it can be executed as the producer.</summary>
    [Fact, Trait("Case", "rules.xunit-producer-hash")]
    public void Generate_ChangedProducerPayload_RejectsHash()
    {
        BuildFixture fixture = CleanTestConsumer();
        string fake = Path.Combine(path1: fixture.DirectoryPath, path2: "changed-producer");
        foreach (string relative in _producerFiles)
        {
            string target = Path.Combine(path1: fake, path2: relative);
            Directory.CreateDirectory(path: Path.GetDirectoryName(path: target)
                    ?? throw new InvalidDataException(message: "Producer target parent missing"));
            File.Copy(sourceFileName: Path.Combine(path1: ProofProtocol.Root,
                    path2: ".phase1/packages/xunit.v3.core.mtp-v2/4.0.2", path3: relative), destFileName: target);
        }

        string task = Path.Combine(path1: fake, path2: _producerFiles[2]);
        byte[] bytes = File.ReadAllBytes(path: task);
        bytes[0] ^= 1;
        File.WriteAllBytes(path: task, bytes: bytes);
        (int Exit, string Output) changed = fixture.Build("-p:_KzXunitPackage=" + fake + "/");
        RequirePolicyDiagnostic(fixture: fixture, result: changed, code: "KZXUNIT004", message: "XUNIT_PRODUCER_HASH");
        changed.Output.ShouldContain(expected: "xunit.v3.msbuildtasks.dll");
        ProofProtocol.Record(id: "rules.xunit-producer-hash", diagnostic: "XUNIT_PRODUCER_HASH_REJECTED",
                location: "copied producer payload rejected; original package remains unchanged");
    }

    private static readonly string[] _producerFiles = ["xunit.v3.core.mtp-v2.4.0.2.nupkg",
        "buildTransitive/xunit.v3.core.mtp-v2.targets", "_content/tasks/netcore/xunit.v3.msbuildtasks.dll"];
    private static readonly (string Name, string Value)[] _suppressionOverrides = [("NoWarn", "SCR0006"),
        ("WarningsNotAsErrors", "SCR0006"), ("RunAnalyzers", "false"), ("RunAnalyzersDuringBuild", "false"),
        ("CodeAnalysisTreatWarningsAsErrors", "false"), ("EnableNETAnalyzers", "false")];

    private static JsonObject EffectiveProperties(string project, params string[] overrides)
    {
        (int Exit, string Output) result = ConfigurationTests.Dotnet(arguments: ["msbuild", project, "-nologo",
            "-getProperty:NoWarn,WarningsNotAsErrors,CodeAnalysisTreatWarningsAsErrors,RunAnalyzers,"
                    + "RunAnalyzersDuringBuild,EnableNETAnalyzers", ..overrides]);
        result.Exit.ShouldBe(expected: 0, customMessage: result.Output);
        return RegisterValidator.Parse(bytes: System.Text.Encoding.UTF8.GetBytes(s: result.Output))
                ["Properties"]?.AsObject() ?? throw new InvalidDataException(message: "EFFECTIVE_PROPERTIES_REQUIRED");
    }

    private static JsonObject ExecutableProperties(string project, params string[] overrides)
    {
        (int Exit, string Output) result = ConfigurationTests.Dotnet(arguments: ["msbuild", project, "-nologo",
            "-getProperty:OutputType,IsTestProject,MSBuildProjectName", ..overrides]);
        result.Exit.ShouldBe(expected: 0, customMessage: result.Output);
        return RegisterValidator.Parse(bytes: System.Text.Encoding.UTF8.GetBytes(s: result.Output))
                ["Properties"]?.AsObject() ?? throw new InvalidDataException(message: "EXECUTABLE_PROPERTIES_REQUIRED");
    }
    private static BuildFixture CleanTestConsumer()
    {
        var fixture = new BuildFixture(tests: true);
        fixture.Restore();
        (int Exit, string Output) clean = fixture.Build();
        clean.Exit.ShouldBe(expected: 0, customMessage: clean.Output);
        return fixture;
    }

    private static void RequirePolicyDiagnostic(BuildFixture fixture, (int Exit, string Output) result,
            string code, string message)
    {
        string file = Path.Combine(path1: fixture.DirectoryPath, path2: "Directory.Xunit.targets");
        string[] lines = File.ReadAllLines(path: file);
        int line = Array.FindIndex(array: lines, match: text => text.Contains(value: "Code=\"" + code + "\"",
                comparisonType: StringComparison.Ordinal)) + 1;
        line.ShouldBeGreaterThan(expected: 0);
        BuildFixture.HasDiagnostic(result: result, id: code, line: line, column: 5,
                file: "Directory.Xunit.targets").ShouldBeTrue(customMessage: result.Output);
        result.Output.ShouldContain(expected: message);
    }
