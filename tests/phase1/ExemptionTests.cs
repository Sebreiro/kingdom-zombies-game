using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Shouldly;
using Xunit;

namespace KingdomZombies.Phase1.Tests;
/// <summary>Exercises exact producer origin, portability and bypass failures through actual compiler
/// consumers.</summary>
public sealed class ExemptionTests
{
    /// <summary>The normal checkout uses the last owned target, exact original task and observed raw source.</summary>
    [Fact, Trait("Case", "rules.xunit-producer-root")]
    public void Generate_NormalCheckout_VerifiesExactProducer()
    {
        string file = Path.Combine(path1: ProofProtocol.Root, path2: ".phase1/temp/xunit-effective-"
                + Guid.NewGuid().ToString(format: "N") + ".xml");
        (int Exit, string Output) result = ConfigurationTests.Dotnet("msbuild", ConfigurationTests.Projects[4],
                "-nologo", "-preprocess:" + file);
        result.Exit.ShouldBe(expected: 0, customMessage: result.Output);
        GeneratedSurfaceScanner.ValidateXunit(root: ProofProtocol.Root, effective: File.ReadAllText(path: file));
        ProofProtocol.Record(id: "rules.xunit-producer-root", diagnostic: "XUNIT_ROOT_PRODUCER_EXACT",
                location: "normal project/task/seed/raw hash/member and effective last target");
    }

    /// <summary>Two distinct real project paths retain one exact source hash and their own project receipts.</summary>
    [Fact, Trait("Case", "rules.xunit-producer-relocation")]
    public void Generate_TwoFreshProjectPaths_PreservesExactSource()
    {
        var first = new BuildFixture(tests: true);
        var second = new BuildFixture(tests: true);
        StringComparer.Ordinal.Equals(x: first.DirectoryPath, y: second.DirectoryPath).ShouldBeFalse();
        first.Restore();
        (int Exit, string Output) firstBuild = first.Build();
        firstBuild.Exit.ShouldBe(expected: 0, customMessage: firstBuild.Output);
        IReadOnlyDictionary<string, string> firstReceipt = GeneratedSurfaceScanner.ValidateXunit(
                root: first.DirectoryPath, effective: first.Preprocess());
        second.Restore();
        (int Exit, string Output) secondBuild = second.Build();
        secondBuild.Exit.ShouldBe(expected: 0, customMessage: secondBuild.Output);
        IReadOnlyDictionary<string, string> secondReceipt = GeneratedSurfaceScanner.ValidateXunit(
                root: second.DirectoryPath, effective: second.Preprocess());
        StringComparer.Ordinal.Equals(x: firstReceipt["Project"], y: secondReceipt["Project"]).ShouldBeFalse();
        firstReceipt["RawSha256"].ShouldBe(expected: secondReceipt["RawSha256"]);
        ProofProtocol.Record(id: "rules.xunit-producer-relocation", diagnostic: "XUNIT_RELOCATION_EXACT",
                location: first.DirectoryPath + " and " + second.DirectoryPath);
    }

    /// <summary>The supported producer remains enabled and its declared logical seed cannot drift.</summary>
    [Fact, Trait("Case", "rules.xunit-producer-seed")]
    public void Configure_SeedOrDisabledGeneration_RejectsDrift()
    {
        BuildFixture fixture = CleanTestConsumer();
        (int Exit, string Output) seed = fixture.Build("-p:KzXunitLogicalSeed=wrong-logical-identity");
        RequirePolicyDiagnostic(fixture: fixture, result: seed, code: "KZXUNIT002", message: "XUNIT_POLICY");
        (int Exit, string Output) disabled = fixture.Build("-p:XunitAutoGeneratedEntryPoint=false");
        RequirePolicyDiagnostic(fixture: fixture, result: disabled, code: "KZXUNIT001", message: "XUNIT_POLICY");
        ProofProtocol.Record(id: "rules.xunit-producer-seed", diagnostic: "XUNIT_POLICY_DRIFT_REJECTED",
                location: "Directory.Xunit.targets exact seed and enabled generation guards");
    }

    /// <summary>Removing only the owned import exposes the original path-bound task and intended generated
    /// errors.</summary>
    [Fact, Trait("Case", "rules.xunit-producer-bypass")]
    public void Configure_OwnedTargetBypass_RejectsGeneratedViolation()
    {
        BuildFixture fixture = CleanTestConsumer();
        string file = Path.Combine(path1: fixture.DirectoryPath, path2: "Directory.Build.targets");
        string[] lines = [..File.ReadAllLines(path: file).Where(predicate: line => !line.Contains(
                value: "Directory.Xunit.targets", comparisonType: StringComparison.Ordinal))];
        File.WriteAllLines(path: file, contents: lines);
        Should.Throw<InvalidDataException>(actual: () => GeneratedSurfaceScanner.ValidateEffectiveTarget(
                source: fixture.Preprocess())).Message.ShouldContain(expected: "XUNIT_TARGET_SHAPE");
        (int Exit, string Output) changed = fixture.Build();
        BuildFixture.HasDiagnostic(result: changed, id: "SCR0001", line: 14, column: 43,
                file: "XunitAutoGeneratedEntryPoint.cs").ShouldBeTrue(customMessage: changed.Output);
        ProofProtocol.Record(id: "rules.xunit-producer-bypass", diagnostic: "XUNIT_TARGET_BYPASS_REJECTED",
                location: "XunitAutoGeneratedEntryPoint.cs(14,43) and effective target");
    }

    /// <summary>Changing the task argument invalidates the generation cache and the exact registered output.</summary>
    [Fact, Trait("Case", "rules.xunit-producer-shape")]
    public void Configure_TargetArgumentMutation_RejectsShape()
    {
        BuildFixture fixture = CleanTestConsumer();
        string file = Path.Combine(path1: fixture.DirectoryPath, path2: "Directory.Xunit.targets");
        string source = File.ReadAllText(path: file);
        File.WriteAllText(path: file, contents: source.Replace(oldValue: "SuffixSeed=\"$(KzXunitLogicalSeed)\"",
                newValue: "SuffixSeed=\"$(MSBuildProjectFullPath)\"", comparisonType: StringComparison.Ordinal));
        Should.Throw<InvalidDataException>(actual: () => GeneratedSurfaceScanner.ValidateEffectiveTarget(
                source: fixture.Preprocess())).Message.ShouldContain(expected: "XUNIT_TARGET_SHAPE");
        (int Exit, string Output) changed = fixture.Build();
        BuildFixture.HasDiagnostic(result: changed, id: "SCR0001", line: 14, column: 43,
                file: "XunitAutoGeneratedEntryPoint.cs").ShouldBeTrue(customMessage: changed.Output);
        ProofProtocol.Record(id: "rules.xunit-producer-shape", diagnostic: "XUNIT_TARGET_SHAPE_REJECTED",
                location: "effective argument plus fresh generated XUnit entry point");
    }

    /// <summary>A changed copied task binary is rejected before it can be executed as the producer.</summary>
    [Fact, Trait("Case", "rules.xunit-producer-hash")]
    public void Generate_ChangedProducerPayload_RejectsHash()
    {
        BuildFixture fixture = CleanTestConsumer();
        string fake = Path.Combine(path1: fixture.DirectoryPath, path2: "changed-producer");
        foreach (string relative in _producerFiles)
        {
            string target = Path.Combine(path1: fake, path2: relative);
            Directory.CreateDirectory(path: Path.GetDirectoryName(path: target)
                    ?? throw new InvalidDataException(message: "Producer target parent missing"));
            File.Copy(sourceFileName: Path.Combine(path1: ProofProtocol.Root,
                    path2: ".phase1/packages/xunit.v3.core.mtp-v2/4.0.2", path3: relative), destFileName: target);
        }

        string task = Path.Combine(path1: fake, path2: _producerFiles[2]);
        byte[] bytes = File.ReadAllBytes(path: task);
        bytes[0] ^= 1;
        File.WriteAllBytes(path: task, bytes: bytes);
        (int Exit, string Output) changed = fixture.Build("-p:_KzXunitPackage=" + fake + "/");
        RequirePolicyDiagnostic(fixture: fixture, result: changed, code: "KZXUNIT004", message: "XUNIT_PRODUCER_HASH");
        changed.Output.ShouldContain(expected: "xunit.v3.msbuildtasks.dll");
        ProofProtocol.Record(id: "rules.xunit-producer-hash", diagnostic: "XUNIT_PRODUCER_HASH_REJECTED",
                location: "copied producer payload rejected; original package remains unchanged");
    }

    private static readonly string[] _producerFiles = ["xunit.v3.core.mtp-v2.4.0.2.nupkg",
        "buildTransitive/xunit.v3.core.mtp-v2.targets", "_content/tasks/netcore/xunit.v3.msbuildtasks.dll"];
    private static BuildFixture CleanTestConsumer()
    {
        var fixture = new BuildFixture(tests: true);
        fixture.Restore();
        (int Exit, string Output) clean = fixture.Build();
        clean.Exit.ShouldBe(expected: 0, customMessage: clean.Output);
        return fixture;
    }

    private static void RequirePolicyDiagnostic(BuildFixture fixture, (int Exit, string Output) result,
            string code, string message)
    {
        string file = Path.Combine(path1: fixture.DirectoryPath, path2: "Directory.Xunit.targets");
        string[] lines = File.ReadAllLines(path: file);
        int line = Array.FindIndex(array: lines, match: text => text.Contains(value: "Code=\"" + code + "\"",
                comparisonType: StringComparison.Ordinal)) + 1;
        line.ShouldBeGreaterThan(expected: 0);
        BuildFixture.HasDiagnostic(result: result, id: code, line: line, column: 5,
                file: "Directory.Xunit.targets").ShouldBeTrue(customMessage: result.Output);
        result.Output.ShouldContain(expected: message);
    }
}
