    /// <summary>Every recognized generated filename and source marker needs authentic producer origin.</summary>
    [Fact, Trait("Case", "rules.generated-claims")]
    public void Generate_AdditionalSourceClaims_RejectsUnprovenOrigin()
    {
        foreach (string path in new[] { "Subject.g.cs", "Subject.g.i.cs", "Subject.Designer.cs",
                "Subject.generated.cs", "TemporaryGeneratedFile_Subject.cs" })
        {
            IReadOnlyList<string> errors = ExemptionValidator.CheckSource(path: path, content: "class Subject {}");
            errors.Count.ShouldBe(expected: 1, customMessage: path);
            errors[0].ShouldBe(expected: "GENERATION_UNPROVEN " + path + "(1,1) generated filename");
        }

        foreach (string marker in new[] { "// <auto-generated/>", "// <autogenerated/>" })
        {
            ExemptionValidator.CheckSource(path: "Subject.cs", content: marker + "\nclass Subject {}")
                    .Count.ShouldBe(expected: 1, customMessage: marker);
        }

        ExemptionValidator.CheckSource(path: "Subject.cs", content: "#nullable disable\nclass Subject {}")
                .ShouldContain(expected: "SUPPRESSION_UNREGISTERED Subject.cs(1,1) nullable disable",
                        comparer: StringComparer.Ordinal);
        ExemptionValidator.CheckSource(path: "Subject.cs",
                content: "using Hidden = System.CodeDom.Compiler.GeneratedCodeAttribute;\n"
                        + "[Hidden(\"fake\",\"1\")] class Subject {}\n").Count.ShouldBe(expected: 1);
        ProofProtocol.Record(id: "rules.generated-claims", diagnostic: "GENERATION_UNPROVEN",
                location: "five recognized suffixes, both markers, aliased attribute and nullable directive");
    }

