    /// <summary>A generated suffix and a marker independently cannot hide a real custom-rule violation.</summary>
    [Fact, Trait("Case", "R-50.negative")]
    public void Generate_FakeSuffixOrMarker_RetainsExactDiagnostic()
    {
        var fixture = new BuildFixture();
        fixture.Restore();
        (int Exit, string Output) clean = fixture.Build();
        clean.Exit.ShouldBe(expected: 0, customMessage: clean.Output);
        string source = BuildFixture.CleanSource.Replace(oldValue: "        return 1;",
                newValue: new string(c: '\n', count: 60) + "        return 1;",
                comparisonType: StringComparison.Ordinal);
        fixture.Write(source: source);
        string normal = Path.Combine(path1: fixture.DirectoryPath, path2: "src/godot-game/core/Subject.cs");
        string fake = Path.Combine(path1: fixture.DirectoryPath, path2: "src/godot-game/core/Subject.g.cs");
        File.Move(sourceFileName: normal, destFileName: fake);
        (int Exit, string Output) suffix = fixture.Build();
        BuildFixture.HasDiagnostic(result: suffix, id: "SCR0006", line: 6, column: 25, file: "Subject.g.cs")
                .ShouldBeTrue(customMessage: suffix.Output);
        ExemptionValidator.CheckSource(path: "Subject.g.cs", content: source).ShouldContain(
                expected: "GENERATION_UNPROVEN Subject.g.cs(1,1) generated filename", comparer: StringComparer.Ordinal);
        File.Move(sourceFileName: fake, destFileName: normal);
        string marker = "// <auto-generated/>\n" + source;
        fixture.Write(source: marker);
        (int Exit, string Output) marked = fixture.Build();
        BuildFixture.HasDiagnostic(result: marked, id: "SCR0006", line: 7, column: 25).ShouldBeTrue(
                customMessage: marked.Output);
        ExemptionValidator.CheckSource(path: "Subject.cs", content: marker).ShouldContain(
                expected: "GENERATION_UNPROVEN Subject.cs(1,1) generated marker", comparer: StringComparer.Ordinal);
        ProofProtocol.Record(id: "R-50.negative", diagnostic: "FAKE_GENERATION_REJECTED",
                location: fixture.DirectoryPath + "/src/godot-game/core/Subject.g.cs(6,25) and Subject.cs(7,25)");
    }

