    private static (string File, int Line) CompanionBody(BuildFixture fixture, bool violate)
    {
        string file = Path.Combine(path1: fixture.DirectoryPath, path2: "src/godot-game/game/proofs/Phase1.cs");
        if (!violate)
        {
            return (file, 0);
        }

        const string Anchor = "        WriteEvidence(assertion: \"ready\");";
        string original = File.ReadAllText(path: file);
        original.Split(separator: Anchor, options: StringSplitOptions.None).Length.ShouldBe(expected: 2);
        string source = original.Replace(oldValue: Anchor,
                newValue: "        _ = System.Math.Abs(-1);\n" + Anchor,
                comparisonType: StringComparison.Ordinal);
        source.ShouldContain(expected: "System.Math.Abs(-1)");
        int line = source[..source.IndexOf(value: "        _ = System.Math.Abs(-1);",
                comparisonType: StringComparison.Ordinal)].Count(predicate: value => value == '\n') + 1;
        File.WriteAllText(path: file, contents: source);
        (int Exit, string Output) changed = fixture.Build();
        BuildFixture.HasDiagnostic(result: changed, id: "SCR0001", line: line, column: 29, file: "Phase1.cs")
                .ShouldBeTrue(customMessage: changed.Output);
        return (file, line);
    }
