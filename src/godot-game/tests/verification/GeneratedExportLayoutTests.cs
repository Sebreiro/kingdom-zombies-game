namespace KingdomZombies.Phase1.Tests;
/// <summary>Authenticates actual Windows SDK export sources and their exact line permissions.</summary>
public sealed class GeneratedExportLayoutTests
{
    /// <summary>Requires observed export source and SDK producer bytes, then runs the real line analyzer.</summary>
    [Fact, Trait("Case", "rules.export-layout-origin")]
    public async Task Check_ExportLayouts_HavePinnedOrigin()
    {
        OperatingSystem.IsWindows().ShouldBeTrue(customMessage: "Windows SDK source proof required");
        using JsonDocument registry = Registry();
        registry.RootElement.GetProperty(propertyName: "sources").GetArrayLength().ShouldBe(expected: 4);
        registry.RootElement.GetProperty(propertyName: "members").GetArrayLength().ShouldBe(expected: 7);
        JsonElement rows = registry.RootElement.GetProperty(propertyName: "exportSources");
        rows.GetArrayLength().ShouldBe(expected: 6);
        DiagnosticAnalyzer analyzer = Analyzer();
        var failures = new List<string>();
        foreach (JsonElement row in rows.EnumerateArray())
        {
            Authenticate(row: row);
            string source = InheritedAnalyzerVerifier.ReadUtf8(path: Local(path: Text(row: row, name: "surface")));
            try
            {
                await AnalyzerVerifier.VerifyAsync(source: source, expected: [], sourcePath: Local(path: Text(
                        row: row, name: "path")), analyzer: analyzer).ConfigureAwait(continueOnCapturedContext: true);
            }
            catch (InvalidOperationException error)
            {
                failures.Add(item: error.Message);
            }
        }

        failures.ShouldBeEmpty(customMessage: string.Join(separator: "\n", values: failures));
        ProofProtocol.Record(id: "rules.export-layout-origin", diagnostic: "SDK_EXPORT_LAYOUT_ORIGIN_EXACT",
                location: "six observed Windows SDK export sources; exact producer, path, bytes and line");
    }

    /// <summary>Rejects independent path, configuration, byte, producer and line impostors with exact spans.</summary>
    [Fact, Trait("Case", "rules.export-layout-boundary")]
    public async Task Check_ExportLayoutPermissions_StayBounded()
    {
        OperatingSystem.IsWindows().ShouldBeTrue(customMessage: "Windows SDK source proof required");
        using JsonDocument registry = Registry();
        DiagnosticAnalyzer analyzer = Analyzer();
        ImmutableArray<MetadataReference> references = AnalyzerVerifier.References();
        foreach (JsonElement row in registry.RootElement.GetProperty(propertyName: "exportSources").EnumerateArray())
        {
            Authenticate(row: row);
            string source = InheritedAnalyzerVerifier.ReadUtf8(path: Local(path: Text(row: row, name: "surface")));
            string path = Local(path: Text(row: row, name: "path")).Replace(oldChar: '\\', newChar: '/');
            string configuration = Text(row: row, name: "configuration");
            string[] paths = ["Subject.cs", path.Replace(oldValue: "/src/", newValue: "/other/"),
                path.Replace(oldValue: "/obj/", newValue: "/other/"), path + ".changed.cs",
                path.Replace(oldValue: Text(row: row, name: "owner"), newValue: Text(row: row, name: "owner")
                        + "-other"),
                path.Replace(oldValue: configuration, newValue: configuration.ToLowerInvariant()),
                path.Replace(oldValue: configuration, newValue: configuration + "Extra"),
                path.Replace(oldValue: configuration, newValue: "Exportdebug"),
                path.Replace(oldValue: configuration, newValue: "exportrelease"),
                path.Replace(oldValue: "AssemblyAttributes.cs", newValue: "assemblyAttributes.cs")];
            foreach (string wrongPath in paths)
            {
                await RejectAsync(source: source, path: wrongPath, analyzer: analyzer, references: references)
                        .ConfigureAwait(continueOnCapturedContext: true);
            }

            foreach (string changed in new[] { source + "\n", source.Replace(oldValue: "// <autogenerated />",
                    newValue: "// handwritten"), source + "\n//" + new string(c: 'a', count: 119), "\n" + source })
            {
                await RejectAsync(source: changed, path: path, analyzer: analyzer, references: references)
                        .ConfigureAwait(continueOnCapturedContext: true);
            }

            RejectOtherLines(source: source, path: path, analyzer: analyzer);
            RejectProducer(row: row);
        }

        ProofProtocol.Record(id: "rules.export-layout-boundary", diagnostic: "SDK_EXPORT_LAYOUT_BOUNDARY_REJECTED",
                location: "six exact paths; independent owner/configuration/case/byte/line/producer controls");
    }

    private static async Task RejectAsync(string source, string path, DiagnosticAnalyzer analyzer,
            ImmutableArray<MetadataReference> references)
    {
        SyntaxTree tree = CSharpSyntaxTree.ParseText(text: source, path: path);
        var compilation = CSharpCompilation.Create(assemblyName: "ExportLineBoundary", syntaxTrees: [tree],
                references: references, options: new CSharpCompilationOptions(outputKind: OutputKind
                        .DynamicallyLinkedLibrary));
        ImmutableArray<Diagnostic> diagnostics = await compilation.WithAnalyzers(analyzers: [analyzer])
                .GetAnalyzerDiagnosticsAsync(cancellationToken: TestContext.Current.CancellationToken)
                .ConfigureAwait(continueOnCapturedContext: true);
        AnalyzerVerifier.Expected[] expected = [.. tree.GetText().Lines.Where(predicate: line => line.Span
                .Length > 120).Select(selector: line => new AnalyzerVerifier.Expected(id: "SCR0007",
                        severity: DiagnosticSeverity.Error, file: path, line: line.LineNumber + 1, column: 121,
                        endLine: line.LineNumber + 1, endColumn: line.Span.Length + 1))];
        expected.Length.ShouldBeGreaterThan(expected: 0);
        AnalyzerVerifier.Match(diagnostics: compilation.GetDiagnostics().AddRange(items: diagnostics),
                expected: expected);
    }

    private static void RejectOtherLines(string source, string path, DiagnosticAnalyzer analyzer)
    {
        SyntaxTree tree = CSharpSyntaxTree.ParseText(text: source, path: path);
        SourceText text = tree.GetText();
        MethodInfo method = analyzer.GetType().Assembly.GetType(name: "Sebreiro.CodeRules.Analyzers.GeneratedLayout")
                ?.GetMethod(name: "IsPermitted", bindingAttr: BindingFlags.Static | BindingFlags.NonPublic)
                ?? throw new InvalidOperationException(message: "Missing exact line permission mechanism");
        foreach (TextLine line in text.Lines)
        {
            (method.Invoke(obj: null, parameters: [tree, text, line]) is true).ShouldBe(expected: line.LineNumber == 3);
        }
    }

    private static void RejectProducer(JsonElement row)
    {
        foreach (string name in new[] { "originSha256", "originSymbol" })
        {
            JsonNode changed = JsonNode.Parse(json: row.GetRawText())
                    ?? throw new InvalidOperationException(message: "Missing origin record");
            changed[name] = "wrong-producer";
            using var subject = JsonDocument.Parse(json: changed.ToJsonString());
            Should.Throw<ShouldAssertException>(actual: () => Authenticate(row: subject.RootElement));
        }
    }

    private static void Authenticate(JsonElement row)
    {
        Text(row: row, name: "platform").ShouldBe(expected: "win32-x64");
        Text(row: row, name: "sdk").ShouldBe(expected: "10.0.404");
        Text(row: row, name: "originSymbol").ShouldBe(expected: "GenerateTargetFrameworkMonikerAttribute");
        string origin = Path.GetFullPath(path: Path.Combine(path1: RuntimeEnvironment.GetRuntimeDirectory(),
                path2: "../../..", path3: Text(row: row, name: "origin")));
        Hash(bytes: File.ReadAllBytes(path: origin)).ShouldBe(expected: Text(row: row, name: "originSha256"));
        byte[] bytes = File.ReadAllBytes(path: Local(path: Text(row: row, name: "surface")));
        bytes.Length.ShouldBe(expected: row.GetProperty(propertyName: "bytes").GetInt32());
        Hash(bytes: bytes).ShouldBe(expected: Text(row: row, name: "sha256"));
        string source = new UTF8Encoding(encoderShouldEmitUTF8Identifier: false, throwOnInvalidBytes: true)
                .GetString(bytes: bytes);
        Hash(bytes: Encoding.UTF8.GetBytes(s: source)).ShouldBe(expected: Text(row: row, name: "textSha256"));
        TextLine line = SourceText.From(text: source).Lines[row.GetProperty(propertyName: "line").GetInt32() - 1];
        line.LineNumber.ShouldBe(expected: 3);
        line.Span.Length.ShouldBe(expected: row.GetProperty(propertyName: "lineLength").GetInt32());
        string path = Text(row: row, name: "path");
        path.ShouldStartWith(expected: Text(row: row, name: "owner") + "/");
        path.ShouldContain(expected: "/obj/" + Text(row: row, name: "configuration") + "/");
    }

    private static DiagnosticAnalyzer Analyzer()
    {
        var assembly = Assembly.Load(rawAssembly: File.ReadAllBytes(path: Local(
                path: "src/godot-game/tools/code-rules/bin/Debug/netstandard2.0/Sebreiro.CodeRules.Analyzers.dll")));
        Type type = assembly.GetType(name: "Sebreiro.CodeRules.Analyzers.LineLengthAnalyzer")
                ?? throw new InvalidOperationException(message: "Missing real line analyzer");
        return Activator.CreateInstance(type: type) as DiagnosticAnalyzer
                ?? throw new InvalidOperationException(message: "Missing analyzer instance");
    }

    private static JsonDocument Registry()
    {
        return JsonDocument.Parse(json: File.ReadAllText(path: Local(
                path: "docs/code/generated-layout-adaptations.json")));
    }

    private static string Text(JsonElement row, string name)
    {
        return row.GetProperty(propertyName: name).GetString()
                ?? throw new InvalidOperationException(message: "Missing export registry string: " + name);
    }

    private static string Local(string path)
    {
        return Path.Combine(path1: ProofProtocol.Root, path2: path);
    }

    private static string Hash(byte[] bytes)
    {
        return Convert.ToHexStringLower(inArray: SHA256.HashData(source: bytes));
    }
}
