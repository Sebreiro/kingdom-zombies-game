using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json.Nodes;
using System.Xml;
using System.Xml.Linq;

namespace KingdomZombies.Phase1.Tests;
/// <summary>Validates exact observed xUnit producer identities and its effective owned build target.</summary>
internal static class GeneratedSurfaceScanner
{
    internal const string Policy = "logical-project-seed-v1";
    internal const string Seed = "KingdomZombies.Phase1.Tests/net10.0/xunit.v3.core.mtp-v2/4.0.2";
    internal const string TaskName = "Xunit.v3.MSBuildTasks.XunitGenerateEntryPoint";
    internal const string TaskHash = "a789901144674a050548b1198067cf5466552a2ed028a10ae629d9f8e369b2a3";
    internal const string PackageHash = "784ed0c6555880636dc3dcf84b27559bcd27f150242c7eff79e6a50d19913d72";
    internal const string TargetsHash = "461321fd8c1e7da66a8291abdc80f95580f29ab2db6bcd1582ed16b6ea915c19";

    /// <summary>Requires fresh-path receipts to name this exact project, producer, raw source and member.</summary>
    internal static IReadOnlyDictionary<string, string> ValidateXunit(string root, string effective)
    {
        ValidateEffectiveTarget(source: effective);
        string relative = "src/godot-game/tests/verification/obj/Debug/net10.0/";
        Dictionary<string, string> receipt = ReadReceipt(file: Path.Combine(path1: root,
                path2: relative + "KzXunitProducer.receipt"));
        Require(value: receipt["Policy"], expected: Policy, diagnostic: "XUNIT_RECEIPT_POLICY");
        Require(value: receipt["Seed"], expected: Seed, diagnostic: "XUNIT_RECEIPT_SEED");
        Require(value: receipt["Task"], expected: TaskName, diagnostic: "XUNIT_RECEIPT_TASK");
        Require(value: receipt["Version"], expected: "4.0.2", diagnostic: "XUNIT_RECEIPT_VERSION");
        Require(value: receipt["TaskSha256"].ToLowerInvariant(), expected: TaskHash, diagnostic: "XUNIT_TASK_HASH");
        Require(value: receipt["PackageSha256"].ToLowerInvariant(), expected: PackageHash,
                diagnostic: "XUNIT_PACKAGE_HASH");
        Require(value: receipt["TargetsSha256"].ToLowerInvariant(), expected: TargetsHash,
                diagnostic: "XUNIT_TARGETS_HASH");
        string policyHash = Hash(file: Path.Combine(path1: root, path2:
                "src/godot-game/build/Directory.Xunit.targets"));
        Require(value: receipt["PolicySha256"].ToLowerInvariant(), expected: policyHash,
                diagnostic: "XUNIT_OWNED_POLICY_HASH");
        Require(value: Path.GetFullPath(path: receipt["Project"]), expected: Path.GetFullPath(path: Path.Combine(
                path1: root, path2: "src/godot-game/tests/verification/KingdomZombies.Phase1.Tests.csproj")),
                diagnostic: "XUNIT_PROJECT_IDENTITY");
        string file = Path.Combine(path1: root, path2: relative + "XunitAutoGeneratedEntryPoint.cs");
        Require(value: Path.GetFullPath(path: receipt["Source"]), expected: Path.GetFullPath(path: file),
                diagnostic: "XUNIT_SOURCE_PATH");
        string actual = Convert.ToHexStringLower(inArray: SHA256.HashData(source: File.ReadAllBytes(path: file)));
        Require(value: receipt["RawSha256"].ToLowerInvariant(), expected: actual,
                diagnostic: "XUNIT_RECEIPT_SOURCE_HASH");
        JsonObject manifest = RegisterValidator.Read(relative: "docs/code/generated-callsite-adaptations.json");
        JsonNode row = manifest["local"]?.AsArray().Single(predicate: item => StringComparer.Ordinal.Equals(
                x: item?["id"]?.GetValue<string>(), y: "KZ-EX-XUNIT-CALLS-01"))
                ?? throw new InvalidDataException(message: "XUNIT_ORIGIN_REQUIRED");
        Require(value: actual, expected: row["sha256"]?.GetValue<string>() ?? "", diagnostic: "XUNIT_RAW_SOURCE_HASH");
        string target = row["target"]?.GetValue<string>() ?? "";
        string adapter = File.ReadAllText(path: Path.Combine(path1: root,
                path2: "src/godot-game/tests/verification/GeneratedCallSiteAdapters.cs"));
        if (Verification.AdapterTargets.Read(source: adapter).Count(predicate: value => StringComparer.Ordinal
                .Equals(x: value, y: target)) != 2)
        {
            throw new InvalidDataException(message: "XUNIT_EXACT_MEMBER_PERMISSIONS");
        }

        return receipt;
    }

    /// <summary>The last effective definition must retain the original task and every exact approved
    /// argument.</summary>
    internal static void ValidateEffectiveTarget(string source)
    {
        using var input = new StringReader(s: source);
        using var reader = XmlReader.Create(input: input, settings: new XmlReaderSettings
        {
            DtdProcessing = DtdProcessing.Prohibit,
            XmlResolver = null,
            MaxCharactersInDocument = 8_000_000
        });
        var document = XDocument.Load(reader: reader);
        XElement target = document.Descendants().LastOrDefault(predicate: element =>
                StringComparer.Ordinal.Equals(x: element.Name.LocalName, y: "Target")
                        && StringComparer.Ordinal.Equals(x: (string?)element.Attribute(name: "Name"),
                                y: "_XunitGenerateEntryPoint"))
                ?? throw new InvalidDataException(message: "XUNIT_TARGET_MISSING");
        XElement[] tasks = [..target.Elements().Where(predicate: item => StringComparer.Ordinal.Equals(
                x: item.Name.LocalName, y: "XunitGenerateEntryPoint"))];
        if (tasks.Length != 1)
        {
            throw new InvalidDataException(message: "XUNIT_EFFECTIVE_TASK");
        }

        foreach ((string Name, string Value) argument in _arguments)
        {
            Require(value: (string?)tasks[0].Attribute(name: argument.Name) ?? "", expected: argument.Value,
                    diagnostic: "XUNIT_TARGET_SHAPE: " + argument.Name);
        }

        XElement[] bindings = [..document.Descendants().Where(predicate: item => StringComparer.Ordinal.Equals(
                x: item.Name.LocalName, y: "UsingTask") && StringComparer.Ordinal.Equals(
                        x: (string?)item.Attribute(name: "TaskName"), y: TaskName))];
        if (bindings.Length != 2 || bindings.Count(predicate: IsCoreBinding) != 1)
        {
            throw new InvalidDataException(message: "XUNIT_PRODUCER_BINDING");
        }
    }

    private static readonly (string Name, string Value)[] _arguments =
    [
        ("SourcePath", "$(_XunitEntryPointPath)"), ("RootNamespace", "$(RootNamespace)"),
        ("SuffixSeed", "$(KzXunitLogicalSeed)"), ("Language", "$(Language)"),
        ("UseMicrosoftTestingPlatformRunner", "$(UseMicrosoftTestingPlatformRunner)")
    ];
    private static readonly UTF8Encoding _strictUtf8 = new(encoderShouldEmitUTF8Identifier: false,
            throwOnInvalidBytes: true);
    private static Dictionary<string, string> ReadReceipt(string file)
    {
        if (new FileInfo(fileName: file).Length > 16_384)
        {
            throw new InvalidDataException(message: "XUNIT_RECEIPT_SIZE");
        }

        var result = new Dictionary<string, string>(comparer: StringComparer.Ordinal);
        foreach (string line in File.ReadAllLines(path: file, encoding: _strictUtf8))
        {
            int separator = line.IndexOf(value: '=');
            if (separator < 1 || !result.TryAdd(key: line[..separator], value: line[(separator + 1)..]))
            {
                throw new InvalidDataException(message: "XUNIT_RECEIPT_STRUCTURE");
            }
        }

        if (result.Count != 11)
        {
            throw new InvalidDataException(message: "XUNIT_RECEIPT_FIELDS");
        }

        return result;
    }

    private static string Hash(string file)
    {
        return Convert.ToHexStringLower(inArray: SHA256.HashData(source: File.ReadAllBytes(path: file)));
    }

    private static bool IsCoreBinding(XElement item)
    {
        string file = (string?)item.Attribute(name: "AssemblyFile") ?? "";
        string normalized = file.Replace(oldChar: '\\', newChar: '/');
        return normalized.EndsWith(value: "/_content/tasks/netcore/xunit.v3.msbuildtasks.dll",
                comparisonType: StringComparison.Ordinal);
    }

    private static void Require(string value, string expected, string diagnostic)
    {
        if (!StringComparer.Ordinal.Equals(x: value, y: expected))
        {
            throw new InvalidDataException(message: diagnostic);
        }
    }
}
